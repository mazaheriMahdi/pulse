pub fn draw_smooth_spans<D: Display>(
    display: &mut D,
    x: u16,
    y: u16,
    w: u16,
    h: u16,
    span_fn: fn(u8) -> (u8, u8, u8, u8),
    fg: Color,
    bg: Color,
) {
    for row in 0..h {
        let (x0, x1, x2, x3) = span_fn(row as u8);
        let py = y + row;

        if x1 == 0 {
            // Entire row is background
            display.fill_rect(x, py, w, 1, bg);
        } else if x2 == 0 {
            // Single stroke span: [0..x0 bg] [x0..x1 fg] [x1..w bg]
            let x0 = x0 as u16;
            let x1 = x1 as u16;
            if x0 > 0 {
                display.fill_rect(x, py, x0, 1, bg);
            }
            display.fill_rect(x + x0, py, x1 - x0, 1, fg);
            if w > x1 {
                display.fill_rect(x + x1, py, w - x1, 1, bg);
            }
        } else {
            // Dual stroke spans: [0..x0 bg] [x0..x1 fg] [x1..x2 bg] [x2..x3 fg] [x3..w bg]
            let x0 = x0 as u16;
            let x1 = x1 as u16;
            let x2 = x2 as u16;
            let x3 = x3 as u16;

            if x0 > 0 {
                display.fill_rect(x, py, x0, 1, bg);
            }
            display.fill_rect(x + x0, py, x1 - x0, 1, fg);
            if x2 > x1 {
                display.fill_rect(x + x1, py, x2 - x1, 1, bg);
            }
            display.fill_rect(x + x2, py, x3 - x2, 1, fg);
            if w > x3 {
                display.fill_rect(x + x3, py, w - x3, 1, bg);
            }
        }
    }
}

pub fn draw_large_digit<D: Display>(
    display: &mut D,
    x: u16,
    y: u16,
    digit: u8,
    fg: Color,
    bg: Color,
) -> u16 {
    let (w, span_fn) = get_lg_digit_info(digit);
    draw_smooth_spans(display, x, y, w, FONT_LG_H, span_fn, fg, bg);
    w
}

