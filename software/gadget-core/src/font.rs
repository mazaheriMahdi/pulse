/// Backwards-compatible glyph lookup for char code points.
#[inline]
pub fn get_glyph(c: char) -> [u8; 5] {
    if c == '°' {
        [0x00, 0x06, 0x09, 0x09, 0x06]
    } else if (c as u32) <= 127 {
        get_glyph_5x7(c as u8)
    } else {
        [0x7F, 0x41, 0x41, 0x41, 0x7F] // Box for unknown non-ASCII
    }
}

/// Renders a single byte glyph using the 5x7 Flash table.
pub fn draw_char_byte<D: Display>(
    display: &mut D,
    x: u16,
    y: u16,
    b: u8,
    fg: Color,
    bg: Color,
    scale: u8,
) {
    let glyph = get_glyph_5x7(b);
    let scale = (scale.max(1)) as u16;

    for (col, &col_byte) in glyph.iter().enumerate() {
        let col_x = x + (col as u16) * scale;
        let mut row = 0;
        while row < 7 {
            let is_on = (col_byte & (1 << row)) != 0;
            let run_color = if is_on { fg } else { bg };
            let start_row = row;
            row += 1;
            while row < 7 && ((col_byte & (1 << row)) != 0) == is_on {
                row += 1;
            }
            let run_len = (row - start_row) * scale;
            display.fill_rect(col_x, y + start_row * scale, scale, run_len, run_color);
        }
    }
    // Trailing spacing column (1 single fill)
    let px = x + 5 * scale;
    display.fill_rect(px, y, scale, 7 * scale, bg);
}

/// Renders a char glyph with scale support.
pub fn draw_char<D: Display>(
    display: &mut D,
    x: u16,
    y: u16,
    c: char,
    fg: Color,
    bg: Color,
    scale: u8,
) {
    if c == '°' {
        let glyph = [0x00, 0x06, 0x09, 0x09, 0x06];
        let scale = (scale.max(1)) as u16;
        for (col, &col_byte) in glyph.iter().enumerate() {
            let col_x = x + (col as u16) * scale;
            let mut row = 0;
            while row < 7 {
                let is_on = (col_byte & (1 << row)) != 0;
                let run_color = if is_on { fg } else { bg };
                let start_row = row;
                row += 1;
                while row < 7 && ((col_byte & (1 << row)) != 0) == is_on {
                    row += 1;
                }
                let run_len = (row - start_row) * scale;
                display.fill_rect(col_x, y + start_row * scale, scale, run_len, run_color);
            }
        }
        let px = x + 5 * scale;
        display.fill_rect(px, y, scale, 7 * scale, bg);
    } else {
        draw_char_byte(display, x, y, c as u8, fg, bg, scale);
    }
}

/// Renders a raw ASCII byte slice. Eliminates UTF-8 validation table and overhead.
pub fn draw_ascii<D: Display>(
    display: &mut D,
    mut x: u16,
    y: u16,
    bytes: &[u8],
    fg: Color,
    bg: Color,
    scale: u8,
) {
    let char_width = 6 * (scale.max(1) as u16);
    for &b in bytes {
        draw_char_byte(display, x, y, b, fg, bg, scale);
        x += char_width;
    }
}

/// Renders a string slice by delegating directly to draw_ascii without UTF-8 re-validation.
pub fn draw_text<D: Display>(
    display: &mut D,
    x: u16,
    y: u16,
    text: &str,
    fg: Color,
    bg: Color,
    scale: u8,
) {
    draw_ascii(display, x, y, text.as_bytes(), fg, bg, scale);
}
