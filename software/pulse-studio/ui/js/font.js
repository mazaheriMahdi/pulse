/**
 * Renders an ASCII string into an SVG circular dot-matrix.
 * Unlit matrix cells are faintly rendered with 0.32 radius in dark grey.
 * Lit matrix cells glow with 0.43 radius in currentColor.
 *
 * @param {string|number} text
 * @param {number} cellSize - Pixel size per dot cell (e.g. 11 for giant numerals, 7 for temp, 3 for headers)
 * @param {string} [className]
 * @returns {string} SVG markup string
 */
export function renderNdot(text, cellSize, className = '') {
  const chars = [...String(text).toUpperCase()];
  const GAP = 1;
  const cols = chars.length * 5 + Math.max(0, chars.length - 1) * GAP;
  const rows = 7;

  let dots = '';
  chars.forEach((ch, charIndex) => {
    const glyph = NDOT_GLYPHS[ch] || NDOT_GLYPHS[' '];
    const offsetX = charIndex * (5 + GAP);

    for (let y = 0; y < rows; y++) {
      for (let x = 0; x < 5; x++) {
        const isLit = glyph[y] && glyph[y][x] === '1';
        const cx = offsetX + x + 0.5;
        const cy = y + 0.5;

        if (isLit) {
          dots += `<circle cx="${cx}" cy="${cy}" r="0.43" fill="currentColor"/>`;
        } else {
          dots += `<circle cx="${cx}" cy="${cy}" r="0.32" fill="var(--dot-off, #1c1c1c)"/>`;
        }
      }
    }
  });

  const width = cols * cellSize;
  const height = rows * cellSize;

  return `<svg class="${className}" width="${width}" height="${height}" viewBox="0 0 ${cols} ${rows}">${dots}</svg>`;
}

/**
 * Renders a horizontal circular dot progress bar.
 *
 * @param {number} percent 0..100
 * @param {number} totalDots Number of dots (e.g. 28, 24, 20)
 * @param {boolean} [isHot=false] If true, active dots turn red
 * @returns {string} HTML markup string
 */
export function renderDotBar(percent, totalDots, isHot = false) {
  const litCount = Math.round(Math.max(0, Math.min(100, percent)) / 100 * totalDots);
  const hotClass = isHot ? 'red' : '';

  let html = `<div class="dotbar-${totalDots}">`;
  for (let i = 0; i < totalDots; i++) {
    const onClass = i < litCount ? `on ${hotClass}` : '';
    html += `<i class="${onClass}"></i>`;
  }
  html += '</div>';
  return html;
}
